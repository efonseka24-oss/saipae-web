export type CategoriaFormato = "RPS" | "RI" | "CCT" | "BODEGA" | "BODEGA_ADMINISTRATIVA";

const MAPAS: Partial<Record<CategoriaFormato, Record<string, number>>> = {
  RPS: rps,
  RI: ri,
  CCT: cct,
  BODEGA: bodega,
  // BODEGA_ADMINISTRATIVA: pendiente, el usuario enviará el mapa de columnas.
};

